'use strict';
const fs=require('fs');
const assert=require('assert');
const src=fs.readFileSync('pristeel-command-center-v2.js','utf8');
const loader=fs.readFileSync('pristeel-ui-standard-v1.js','utf8');
assert.ok(src.includes('PPPP Command Center v2'),'command center module missing');
assert.ok(src.includes('PSTCommandCenterV2'),'command center export missing');
assert.ok(loader.includes('pristeel-command-center-v2.js'),'UI loader must load command center v2');
assert.ok(!loader.includes('pristeel-ui-balanced-v1.js'),'retired mixed Home overlay must not load');
assert.ok(!loader.includes('pristeel-home-insights-v1.js'),'retired Home insights overlay must not load');
assert.ok(!/new\s+MutationObserver\s*\(/.test(src),'command center must not own a MutationObserver');
assert.ok(!src.includes('setInterval('),'command center must not poll with setInterval');
assert.ok(!/\b(?:PATCH|DELETE|PUT)\b/.test(src),'command center must not contain business mutation methods');
assert.ok(src.includes('pppp_home_current_actions_v1'),'confirmed action source missing');
assert.ok(src.includes('pppp_automation_health_v1'),'automation health surface missing');
assert.ok(src.includes('Next 7 days'),'seven-day outlook missing');
assert.ok(src.includes('Client concentration'),'client concentration analysis missing');
assert.ok(src.includes('Recent project movement'),'project movement surface missing');
assert.ok(src.includes('!actionIds[S(p.id)]'),'Home anti-duplication rule missing');
assert.ok(src.includes('Financial attention'),'finance exception surface missing');
assert.ok(src.includes('Opportunity pipeline'),'commercial pipeline missing');
assert.ok(src.includes('ASK PPPP'),'Ask PPPP English UI missing');
assert.ok(src.includes('>.pst-live-head')&&src.includes('>.pst-live-needs')&&src.includes('>.pst-live-status'),'legacy Home sections must be explicitly retired from visible Home');
assert.ok(src.includes("data-cc-area=\"projects\"")||src.includes("data-cc-area=\\\"projects\\\""),'click-through project navigation missing');
assert.ok(src.includes("area==='finance'")&&src.includes("area==='opportunities'")&&src.includes("area==='system'"),'module drill-down navigation missing');
console.log('PPPP Command Center v2 single-owner safety smoke: OK');
