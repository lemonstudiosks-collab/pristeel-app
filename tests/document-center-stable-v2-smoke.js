const fs=require('fs');
const assert=require('assert');
const {JSDOM}=require('jsdom');
(async()=>{
 const src=fs.readFileSync('pristeel-document-center-stable-v2.js','utf8');
 const adjustmentsV3=fs.readFileSync('pristeel-document-adjustments-v3.js','utf8');
 const bootstrap=fs.readFileSync('pristeel-project-emails.js','utf8');
 const manifest=JSON.parse(fs.readFileSync('runtime-manifest.json','utf8'));
 assert(!/MutationObserver\s*\(|setInterval\s*\(/.test(src),'Document center must not use global observer or polling');
 assert(!bootstrap.includes('pristeel-document-adjustments.js'),'Legacy document adjustments v1 must not return to runtime bootstrap');
 assert(bootstrap.includes('pristeel-document-adjustments-v3.js'),'Document adjustments v3 must remain in runtime bootstrap');
 assert((manifest.deprecatedForbidden||[]).includes('pristeel-document-adjustments.js'),'Manifest must forbid legacy document adjustments v1');
 const documentArea=(manifest.areas||[]).find(x=>x.area==='document-center');
 assert(documentArea&&(documentArea.finalOwners||[]).includes('pristeel-document-adjustments-v3.js'),'Manifest must classify document adjustments v3 as a document-center owner');
 const dom=new JSDOM('<!doctype html><html><head></head><body><div class="content"></div><div class="page" id="page-home"></div></body></html>',{runScripts:'outside-only',url:'https://example.test/'});
 const w=dom.window;w.scrollTo=()=>{};w.supaFetch=async(path)=>{
   if(path.startsWith('documents_registry?'))return[{id:'q1',doc_nr:'Q-1',project:'P1',client:'C1',total_eur:100,created_at:'2026-08-07'}];
   if(path.startsWith('invoices_out?'))return[{id:'i1',invoice_nr:'I-1',project:'P1',client:'C1',gross_amount:120,date:'2026-08-07',currency:'EUR',items:[{description:'Steel',kg:516,price_kg:3.1}]}];
   return[];
 };
 w.eval(src);
 w.eval(adjustmentsV3);
 assert(w.PSTDocumentCenterStableV2,'Stable document center API missing');
 assert.strictEqual(typeof w.pstOpenAdjustment,'function','Document adjustments v3 public opener missing');
 assert.strictEqual(typeof w.pstSaveAdjustment,'function','Document adjustments v3 public save API missing');
 assert.strictEqual(typeof w.pstOpenAdjustmentDetail,'function','Document adjustments v3 detail API missing');
 assert.strictEqual(w.pstOpenDocumentCenter('offer'),true,'Document center did not open');
 await w.PSTDocumentCenterStableV2.load();
 assert(w.PSTDocumentCenterStableV2.state.all.length>=2,'Document center did not combine offers and invoices');
 assert(w.document.getElementById('pst-dc-list').textContent.includes('Q-1'),'Offer missing from stable register');
 await w.pstOpenAdjustment('credit_note','i1');
 assert(w.document.getElementById('pst-adj-bg'),'Document adjustments v3 did not open from current Document Center compatibility state');
 assert(w.document.getElementById('pst-adj-v3-lines'),'Document adjustments v3 UI did not render');
 dom.window.close();console.log('Document center stable v2 smoke test passed.');
})().catch(e=>{console.error(e);process.exit(1);});
