import assert from 'node:assert/strict';
import fs from 'node:fs';
import { JSDOM } from 'jsdom';

const dom=new JSDOM('<!doctype html><html id="pst-spie-platform" class="pst-spie-standard"><head></head><body><div class="content"><section class="page active" id="page-workspace-home"></section></div></body></html>',{url:'https://example.test/',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,d=w.document,requests=[],writes=[];
w.scrollTo=()=>{};
w.pstWorkspaceGo=()=>{d.querySelectorAll('.page').forEach(p=>{p.classList.toggle('active',p.id==='page-workspace-home');p.style.display=p.id==='page-workspace-home'?'block':'none'});};
w.supaFetch=async (p,method)=>{
 requests.push(p);if(method&&method!=='GET'){writes.push({p,method});throw Error('Unexpected write');}
 if(p.startsWith('pppp_representation_opportunity_targets_v1'))return [{opportunity_id:'opp1',target_id:'epc1',candidate_role:'lead_epc_candidate',company_fit_status:'verified'}];
 if(p.startsWith('pppp_representation_opportunities_v1'))return [{id:'opp1',source_key:'test:project',project_name:'Test JV',status:'pipeline',verification_status:'verified',procurement_stage:'Tender open'}];
 if(p.startsWith('pppp_representation_targets_v1'))return [{id:'rep1',target_type:'representation',source_key:'rep:test',company_name:'Test Manufacturer',country:'DE',stage:'found',sector:'Industry',capital_fit:'good',contact_email:'test@example.test'},{id:'epc1',target_type:'lead_epc_candidate',company_name:'Test EPC',country:'EU',stage:'found'}];
 return [];
};
for(const file of ['pristeel-representations-v1.js','pristeel-representation-opportunities-v2.js','pristeel-representation-discovery-v1.js'])w.eval(fs.readFileSync(file,'utf8'));
d.dispatchEvent(new w.Event('DOMContentLoaded'));
const settle=()=>new Promise(resolve=>w.setTimeout(resolve,30));
await settle();w.PSTRepresentationsV1.open();await settle();
const page=d.getElementById('page-representations'),side=page.querySelector('[data-rep-sidebar]'),work=page.querySelector('[data-rep-work-main]');
assert(side&&work,'One contextual sidebar and one content region');
assert.equal(page.querySelectorAll('[data-rep-sidebar]').length,1);
assert.equal(page.querySelector('.pst-rep-page').getAttribute('data-pst-font-lock'),'1');
w.eval(fs.readFileSync('pristeel-platform-readability-v1.js','utf8'));
const titles=[...side.querySelectorAll('.pst-rep-branch-title')];
const before=titles.map(el=>el.className);
w.PSTPlatformReadabilityV1.apply(d);
assert.deepEqual(titles.map(el=>el.className),before,'Delayed readability cannot restyle module navigation');
assert.equal(page.querySelectorAll('[class*="pst-rd-"]').length,0,'Static Home typography keeps the module stable');
assert(side.contains(page.querySelector('[data-rep-switch]')),'Branches belong to left navigation');
assert(side.contains(page.querySelector('[data-rep-target-controls]')),'Filters belong to left navigation');
assert(work.contains(page.querySelector('[data-rep-target-view]')),'Companies remain in the main region');
assert(work.contains(page.querySelector('[data-rep-opportunity-view]')));
assert(work.contains(page.querySelector('[data-rep-discovery-view]')));
assert.equal(page.querySelector('[data-rep-search]').getAttribute('aria-label'),'Kërko kompani ose domen');
assert.equal(page.querySelectorAll('[data-rep-id]').length,1,'EPC candidates stay out of representation list');
page.querySelector('[data-rep-id]').click();
assert.equal(w.PSTRepresentationsV1.snapshot().view,'profile');
assert.equal(page.querySelector('[data-rep-profile-view]').hidden,false);
assert.notEqual(page.querySelector('[data-rep-switch]').style.display,'none','Branch navigation stays available in company dossiers');
page.querySelector('[data-rep-back]').click();
assert.equal(w.PSTRepresentationsV1.snapshot().view,'list');
page.querySelector('[data-rep-mode="opportunities"]').click();await settle();
assert.equal(page.querySelector('[data-rep-target-controls]').hidden,true);
assert.match(page.querySelector('[data-rep-opportunity-view]').textContent,/Test JV/);
page.querySelector('[data-opp-open-project]').click();await settle();
assert(page.querySelector('[data-opp-projects-back]'),'Project workspace retains its back action');
page.querySelector('[data-opp-projects-back]').click();
const reads=requests.length;
page.querySelector('[data-rep-mode="targets"]').click();
page.querySelector('[data-rep-mode="opportunities"]').click();await settle();
assert.equal(requests.length,reads,'Revisiting a loaded branch does not reread Supabase');
page.querySelector('[data-rep-mode="targets"]').click();
assert.equal(page.querySelector('[data-rep-target-controls]').hidden,false);
assert.equal(page.querySelector('[data-rep-target-view]').hidden,false);
page.querySelector('[data-rep-mode="discovery"]').click();await settle();
assert.equal(page.querySelector('[data-rep-discovery-view]').hidden,false);
assert.equal(page.querySelector('[data-rep-target-controls]').hidden,true);
page.querySelector('[data-rd-back]').click();
assert.equal(page.querySelector('[data-rep-target-controls]').hidden,false);
assert.equal(page.querySelector('[data-rep-target-view]').hidden,false);
page.querySelector('[data-rep-home]').click();
assert(d.getElementById('page-workspace-home').classList.contains('active'));
assert.deepEqual(writes,[],'Navigation and presentation never mutate business data');
dom.window.close();
console.log('Representations Home standard: PASS (sidebar, dossiers, JV, discovery, back, cached reads, no writes)');
