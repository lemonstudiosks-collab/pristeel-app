const fs=require('fs');
const assert=require('assert');
const {JSDOM}=require('jsdom');

(async()=>{
 const source=fs.readFileSync('pristeel-supplier-capability-manager-v1.js','utf8');
 assert(!/MutationObserver|setInterval\s*\(/.test(source),'Supplier capability manager must not observe or poll');
 assert(!/supaFetch\(['"]suppliers/.test(source),'Capability manager must not use a non-existent suppliers table');
 const dom=new JSDOM(`<!doctype html><html><body><div id="page-workspace-project" class="pf2-on"><section class="pf2-card"><header><div><b>Routing</b></div></header><div>old</div></section></div></body></html>`,{runScripts:'outside-only',url:'https://example.test/'});
 const w=dom.window,queries=[],writes=[];
 w.__pstIntegrityLastData={project:{deal_type:'full'}};
 w.PSTProjectFirstV2={capabilities:()=>['profile']};
 w.confirm=()=>true;
 w.supaFetch=async (path,method,body)=>{if(method){writes.push({path,method,body});return[];}queries.push(path);return[{id:'p1',name:'Steel Trade',country:'DE',city:'Duisburg',categories:['profiles'],business_type:'supplier'}];};
 w.eval(source);
 await w.PSTSupplierCapabilityManagerV1.inject();
 assert(queries.some(x=>x.startsWith('partners?relation=cs.{supplier}')),'Supplier routing must use the canonical partners registry');
 const txt=w.document.querySelector('.pf2-card').textContent;
 assert(txt.includes('Steel Trade'),'Tagged partner was not routed');
 assert(txt.includes('Profile'),'Canonical profile category was not displayed');
 assert(txt.includes('Aktiva')&&txt.includes('Kentaur'),'Fixed producers must remain available for production projects');
 assert.deepStrictEqual(Array.from(w.PSTSupplierCapabilityManagerV1._test.mapCaps(['profile','tuba'])),['profiles','tubes'],'Detected capabilities were not mapped to canonical categories');
 await w.PSTSupplierCapabilityManagerV1.open();
 const row=w.document.querySelector('.pst-scm-row[data-id="p1"]');
 assert(row,'Partner category editor did not render');
 const gal=row.querySelector('input[value="galvanizing"]');gal.checked=true;
 row.querySelector('[data-save="p1"]').click();
 await new Promise(r=>setTimeout(r,20));
 const patch=writes.find(x=>x.path==='partners?id=eq.p1'&&x.method==='PATCH');
 assert(patch&&patch.body.categories.includes('profiles')&&patch.body.categories.includes('galvanizing'),'Human-corrected tags were not saved to partners.categories');
 dom.window.close();console.log('Supplier capability manager smoke test passed.');
})().catch(e=>{console.error(e);process.exit(1);});
